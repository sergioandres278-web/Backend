package com.agencytrip.agencytripapi.infrastructure.adapter.in.web;

import static org.springframework.security.test.web.servlet.request.SecurityMockMvcRequestPostProcessors.jwt;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.agencytrip.agencytripapi.application.dto.Requests;
import com.agencytrip.agencytripapi.application.service.UserService;
import com.agencytrip.agencytripapi.domain.model.User;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.List;
import javax.crypto.SecretKey;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.HttpStatus;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;
import org.springframework.security.oauth2.jwt.JwsHeader;
import java.util.UUID;
import org.springframework.security.oauth2.jose.jws.MacAlgorithm;
import org.springframework.security.oauth2.jwt.JwtClaimsSet;
import org.springframework.security.oauth2.jwt.JwtEncoder;
import org.springframework.security.oauth2.jwt.JwtEncoderParameters;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;

/**
 * Tests covering JWT generation, validation and basic authentication scenarios.
 * Uses the real Spring Security configuration (no mocks) with the test profile.
 */
@SpringBootTest
@ActiveProfiles("test")
class JwtSecurityTests {

    @Autowired private WebApplicationContext wac;
    private MockMvc mockMvc;
    @Autowired private UserService userService;
    @Autowired private JwtEncoder jwtEncoder;
    @Autowired private SecretKey jwtKey;

    private String testEmail;
    private final String testPassword = "SecretPass123";
    private User testUser;

    @BeforeEach
    void setUp() {
        this.mockMvc = MockMvcBuilders.webAppContextSetup(this.wac).build();
        // Register a fresh user for each test (id will be generated by DB).
        testEmail = "testuser+" + UUID.randomUUID().toString() + "@example.com";
        Requests.Register reg = new Requests.Register("Test", "User", testEmail, testPassword);
        testUser = userService.register(reg);
    }

    @AfterEach
    void tearDown() {
        // Clean up the created user (disable to avoid side effects).
        try { userService.disable(testUser.getIdUsuario(), null); } catch (Exception ignored) {}
    }

    @Test
    @DisplayName("Login with correct credentials returns a JWT token")
    void loginSuccessGeneratesToken() {
        Requests.Login login = new Requests.Login(testEmail, testPassword);
        var result = userService.login(login);
        assert result.token() != null && !result.token().isBlank();
    }

    @Test
    @DisplayName("Login with wrong password returns UNAUTHORIZED (401)")
    void loginFailureWrongPassword() {
        Requests.Login login = new Requests.Login(testEmail, "WrongPassword");
        try {
            userService.login(login);
            assert false; // should not reach here
        } catch (Exception e) {
            assert e instanceof com.agencytrip.agencytripapi.application.service.BusinessException;
            var be = (com.agencytrip.agencytripapi.application.service.BusinessException) e;
            assert be.status() == HttpStatus.UNAUTHORIZED;
        }
    }

    @Test
    @DisplayName("Access protected endpoint without token returns 401")
    void protectedEndpointWithoutToken() throws Exception {
        mockMvc.perform(get("/api/Reservas"))
                .andExpect(status().isUnauthorized());
    }

    @Test
    @DisplayName("Expired JWT is rejected with 401")
    void expiredJwtRejected() throws Exception {
        JwtClaimsSet claims = JwtClaimsSet.builder()
                .issuer("test-issuer")
                .issuedAt(Instant.now().minus(2, ChronoUnit.HOURS))
                .expiresAt(Instant.now().minus(1, ChronoUnit.MINUTES))
                .subject("test")
                .claim("userId", testUser.getIdUsuario())
                .claim("email", testUser.getCorreo())
                .claim("roles", List.of("ROLE_CLIENTE"))
                .build();
        String token = jwtEncoder.encode(JwtEncoderParameters.from(JwsHeader.with(MacAlgorithm.HS256).build(), claims)).getTokenValue();
        mockMvc.perform(get("/api/Reservas").header("Authorization", "Bearer " + token))
                .andExpect(status().isUnauthorized());
    }

    @Test
    @DisplayName("Malformed JWT is rejected with 401")
    void malformedJwtRejected() throws Exception {
        mockMvc.perform(get("/api/Reservas").header("Authorization", "Bearer not.a.valid.token"))
                .andExpect(status().isUnauthorized());
    }

    @Test
    @DisplayName("JWT with wrong issuer is rejected with 401")
    void wrongIssuerJwtRejected() throws Exception {
        JwtClaimsSet claims = JwtClaimsSet.builder()
                .issuer("wrong-issuer")
                .issuedAt(Instant.now())
                .expiresAt(Instant.now().plus(1, ChronoUnit.HOURS))
                .subject("test")
                .claim("userId", testUser.getIdUsuario())
                .claim("email", testUser.getCorreo())
                .claim("roles", List.of("ROLE_CLIENTE"))
                .build();
        String token = jwtEncoder.encode(JwtEncoderParameters.from(JwsHeader.with(MacAlgorithm.HS256).build(), claims)).getTokenValue();
        mockMvc.perform(get("/api/Reservas").header("Authorization", "Bearer " + token))
                .andExpect(status().isUnauthorized());
    }

    @Test
    @DisplayName("JWT with wrong audience is rejected with 401")
    void wrongAudienceJwtRejected() throws Exception {
        // The validator expects the audience defined in application-test.yml ("test-audience").
        JwtClaimsSet claims = JwtClaimsSet.builder()
                .issuer("test-issuer")
                .audience(List.of("wrong-audience"))
                .issuedAt(Instant.now())
                .expiresAt(Instant.now().plus(1, ChronoUnit.HOURS))
                .subject("test")
                .claim("userId", testUser.getIdUsuario())
                .claim("email", testUser.getCorreo())
                .claim("roles", List.of("ROLE_CLIENTE"))
                .build();
        String token = jwtEncoder.encode(JwtEncoderParameters.from(JwsHeader.with(MacAlgorithm.HS256).build(), claims)).getTokenValue();
        mockMvc.perform(get("/api/Reservas").header("Authorization", "Bearer " + token))
                .andExpect(status().isUnauthorized());
    }
}
